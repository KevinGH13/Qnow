#!/usr/bin/env bash
# One-time: start using Prisma Migrate on a database created with `db push`.
# 1) Checks the database already matches prisma/schema.prisma.
# 2) Writes prisma/migrations/0_init from the schema.
# 3) Marks 0_init as already applied (nothing is executed against your data).
# Usage: npm run db:baseline   (uses DIRECT_URL, or DATABASE_URL, from .env)
set -euo pipefail
cd "$(dirname "$0")/.."

if [ -d prisma/migrations/0_init ]; then
  echo "prisma/migrations/0_init already exists. Only marking it as applied."
else
  echo "Checking the database matches the schema…"
  if ! npx prisma migrate diff --from-config-datasource --to-schema prisma/schema.prisma --exit-code >/dev/null; then
    echo "The database differs from prisma/schema.prisma. Run 'npm run db:push' first (or review the diff):"
    npx prisma migrate diff --from-config-datasource --to-schema prisma/schema.prisma || true
    exit 1
  fi
  mkdir -p prisma/migrations/0_init
  npx prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script -o prisma/migrations/0_init/migration.sql
  printf '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n' > prisma/migrations/migration_lock.toml
  echo "Wrote prisma/migrations/0_init/migration.sql"
fi

npx prisma migrate resolve --applied 0_init
echo "Done. From now on: 'npm run db:migrate' for schema changes; Vercel runs 'prisma migrate deploy' on each deploy."
